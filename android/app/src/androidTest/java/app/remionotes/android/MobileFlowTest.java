package app.remionotes.android;

import android.view.KeyEvent;
import androidx.test.core.app.ActivityScenario;
import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.platform.app.InstrumentationRegistry;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.json.JSONObject;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import static org.junit.Assert.*;

@RunWith(AndroidJUnit4.class)
public class MobileFlowTest {
    private ActivityScenario<MainActivity> scenario;

    private String js(String expression) throws Exception {
        CountDownLatch done = new CountDownLatch(1);
        String[] result = new String[1];
        scenario.onActivity(activity -> activity.getBridge().getWebView().evaluateJavascript(
            "(()=>{" + expression + "})()", value -> { result[0] = value; done.countDown(); }));
        assertTrue("WebView did not respond", done.await(10, TimeUnit.SECONDS));
        return result[0];
    }
    private void waitFor(String condition) throws Exception {
        long deadline = System.currentTimeMillis() + 20000;
        while (System.currentTimeMillis() < deadline) {
            if ("true".equals(js("return !!(" + condition + ");"))) return;
            Thread.sleep(200);
        }
        fail("Timed out: " + condition + "; page: " + js("return document.body.innerText;"));
    }
    private void input(String selector, String value) throws Exception {
        js("const e=document.querySelector(" + JSONObject.quote(selector) + ");" +
            "const p=e.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;" +
            "Object.getOwnPropertyDescriptor(p,'value').set.call(e," + JSONObject.quote(value) + ");" +
            "e.dispatchEvent(new Event('input',{bubbles:true}));return true;");
    }
    @Test public void createSearchRestartAndBack() throws Exception {
        String note = "Android実機テスト " + System.currentTimeMillis();
        scenario = ActivityScenario.launch(MainActivity.class);
        try {
            waitFor("document.querySelector('.mobile-add')");
            assertEquals("\"https://localhost\"", js("return location.origin;"));
            // Block only this WebView's network. Device connectivity is unchanged.
            scenario.onActivity(a -> a.getBridge().getWebView().getSettings().setBlockNetworkLoads(true));
            js("document.querySelector('.mobile-add').click();return true;");
            waitFor("document.querySelector('#card-content')");
            input("#card-content", note);
            js("document.querySelector('button[type=submit]').click();return true;");
            waitFor("!document.querySelector('#card-content') && document.body.innerText.includes(" + JSONObject.quote(note) + ")");
            scenario.recreate();
            waitFor("document.querySelector('.mobile-add') && document.body.innerText.includes(" + JSONObject.quote(note) + ")");
            js("[...document.querySelectorAll('.mobile-navigation button')].find(e=>e.innerText.includes('検索')).click();return true;");
            waitFor("document.querySelector('input[aria-label=\"検索キーワード\"]')");
            input("input[aria-label=\"検索キーワード\"]", note);
            waitFor("document.querySelector('.search-result')?.innerText.includes(" + JSONObject.quote(note) + ")");
            InstrumentationRegistry.getInstrumentation().sendKeyDownUpSync(KeyEvent.KEYCODE_BACK);
            waitFor("!document.querySelector('input[aria-label=\"検索キーワード\"]')");
            assertEquals("false", js("return !!document.querySelector('.fatal');"));
            // Remove only the card generated by this test through the normal UI.
            js("[...document.querySelectorAll('.note-card')].find(e=>e.innerText.includes(" + JSONObject.quote(note) + ")).querySelector('.more').click();return true;");
            waitFor("[...document.querySelectorAll('.popover button')].some(e=>e.innerText==='削除')");
            js("[...document.querySelectorAll('.popover button')].find(e=>e.innerText==='削除').click();return true;");
            waitFor("[...document.querySelectorAll('button')].some(e=>e.innerText==='削除する')");
            js("[...document.querySelectorAll('button')].find(e=>e.innerText==='削除する').click();return true;");
            waitFor("![...document.querySelectorAll('.note-card')].some(e=>e.innerText.includes(" + JSONObject.quote(note) + "))");
        } finally { scenario.close(); }
    }
}
